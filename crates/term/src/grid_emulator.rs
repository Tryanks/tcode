//! Host-side terminal emulation and rendering snapshots with their scrollback.

use std::{
    collections::HashMap,
    sync::{
        Arc, Mutex, Weak,
        atomic::{AtomicUsize, Ordering},
    },
    thread,
};

// rio's synchronized-update deadlines use its own clock, which is `web_time`
// on wasm; mixing in `std::time::Instant` would not compile there.
use rio_vt::time::Instant;
use rio_vt::{
    ansi::CursorShape as RioCursorShape,
    clipboard::ClipboardType,
    config::colors::{ColorRgb, NamedColor},
    crosswords::{
        Crosswords, CrosswordsSize,
        grid::Dimensions,
        pos::{Column, Line, Pos},
    },
    event::{EventListener, RioEvent, TerminalDamage, WindowId, WindowSize, sync::FairMutex},
    performer::handler::Processor,
};

use crate::{DEFAULT_CELL_HEIGHT_PX, DEFAULT_CELL_WIDTH_PX, TermSnapshot, sync::MutexExt as _};

/// Data emitted by terminal emulation.
///
/// `Input` contains protocol replies generated by the emulator (for example a
/// device-attributes response) and must be sent back to the host PTY.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum GridEvent {
    Wakeup,
    TitleChanged(Option<String>),
    CursorBlinkingChanged,
    Bell,
    Input(Vec<u8>),
    ClipboardStore { kind: ClipboardType, text: String },
}

/// The host's terminal state machine. Selection and the scrolled viewport are
/// each client's own; this grid always shows the bottom of its scrollback.
///
/// This type accepts raw output bytes and owns all terminal grid state. It has
/// no PTY, child-process, or platform process types in its public API.
#[derive(Clone)]
pub struct GridEmulator {
    core: Arc<GridCore>,
    events: async_channel::Receiver<GridEvent>,
}

struct GridCore {
    state: FairMutex<GridState>,
    notifications: async_channel::Sender<GridEvent>,
    osc_title: Arc<Mutex<Option<String>>>,
    fallback_title: Mutex<String>,
    lifecycle: Mutex<GridLifecycle>,
    size: Arc<AtomicGridSize>,
}

struct GridState {
    term: Crosswords<GridListener>,
    parser: Processor,
}

#[derive(Default)]
struct GridLifecycle {
    exited: bool,
    exit_code: Option<i32>,
}

struct AtomicGridSize {
    cols: AtomicUsize,
    rows: AtomicUsize,
    cell_width_px: AtomicUsize,
    cell_height_px: AtomicUsize,
}

impl AtomicGridSize {
    fn new(size: GridSize) -> Self {
        Self {
            cols: AtomicUsize::new(size.cols),
            rows: AtomicUsize::new(size.rows),
            cell_width_px: AtomicUsize::new(size.cell_width_px as usize),
            cell_height_px: AtomicUsize::new(size.cell_height_px as usize),
        }
    }

    fn load(&self) -> GridSize {
        GridSize {
            cols: self.cols.load(Ordering::Relaxed),
            rows: self.rows.load(Ordering::Relaxed),
            cell_width_px: self
                .cell_width_px
                .load(Ordering::Relaxed)
                .min(u32::MAX as usize) as u32,
            cell_height_px: self
                .cell_height_px
                .load(Ordering::Relaxed)
                .min(u32::MAX as usize) as u32,
        }
    }

    fn store(&self, size: GridSize) {
        self.cols.store(size.cols, Ordering::Relaxed);
        self.rows.store(size.rows, Ordering::Relaxed);
        self.cell_width_px
            .store(size.cell_width_px as usize, Ordering::Relaxed);
        self.cell_height_px
            .store(size.cell_height_px as usize, Ordering::Relaxed);
    }

    fn window_size(&self) -> WindowSize {
        self.load().window_size()
    }
}

#[derive(Clone)]
struct GridListener {
    notifications: async_channel::Sender<GridEvent>,
    osc_title: Arc<Mutex<Option<String>>>,
    size: Arc<AtomicGridSize>,
}

impl EventListener for GridListener {
    fn send_event(&self, event: RioEvent, _window_id: WindowId) {
        match event {
            RioEvent::Title(_, title) => {
                *self.osc_title.lock_recover() = Some(title.clone());
                let _ = self
                    .notifications
                    .try_send(GridEvent::TitleChanged(Some(title)));
            }
            RioEvent::ResetTitle => {
                *self.osc_title.lock_recover() = None;
                let _ = self.notifications.try_send(GridEvent::TitleChanged(None));
            }
            RioEvent::CursorBlinkingChange | RioEvent::CursorBlinkingChangeOnRoute(_) => {
                let _ = self
                    .notifications
                    .try_send(GridEvent::CursorBlinkingChanged);
            }
            RioEvent::Bell(_) => {
                let _ = self.notifications.try_send(GridEvent::Bell);
            }
            RioEvent::Render
            | RioEvent::RenderRoute(_)
            | RioEvent::TerminalDamaged(_)
            | RioEvent::PrepareRender(_)
            | RioEvent::PrepareRenderOnRoute(_, _) => {
                let _ = self.notifications.try_send(GridEvent::Wakeup);
            }
            RioEvent::PtyWrite(_, text) => {
                let _ = self
                    .notifications
                    .try_send(GridEvent::Input(text.into_bytes()));
            }
            RioEvent::ColorRequest(_, index, format) => {
                let bytes = format(query_color(index)).into_bytes();
                let _ = self.notifications.try_send(GridEvent::Input(bytes));
            }
            RioEvent::TextAreaSizeRequest(_, format) => {
                let bytes = format(self.size.window_size()).into_bytes();
                let _ = self.notifications.try_send(GridEvent::Input(bytes));
            }
            RioEvent::ClipboardStore(kind, text) => {
                let _ = self
                    .notifications
                    .try_send(GridEvent::ClipboardStore { kind, text });
            }
            RioEvent::ClipboardLoad(_, _, formatter) => {
                // OSC 52 reads are denied by returning an empty clipboard.
                let _ = self
                    .notifications
                    .try_send(GridEvent::Input(formatter("").into_bytes()));
            }
            _ => {}
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
struct GridSize {
    cols: usize,
    rows: usize,
    cell_width_px: u32,
    cell_height_px: u32,
}

impl Dimensions for GridSize {
    fn total_lines(&self) -> usize {
        self.rows
    }

    fn screen_lines(&self) -> usize {
        self.rows
    }

    fn columns(&self) -> usize {
        self.cols
    }
}

impl GridSize {
    fn crosswords_size(self) -> CrosswordsSize {
        let width = (self.cols as u64)
            .saturating_mul(u64::from(self.cell_width_px))
            .min(u64::from(u32::MAX)) as u32;
        let height = (self.rows as u64)
            .saturating_mul(u64::from(self.cell_height_px))
            .min(u64::from(u32::MAX)) as u32;
        CrosswordsSize::new_with_dimensions(
            self.cols,
            self.rows,
            width,
            height,
            self.cell_width_px,
            self.cell_height_px,
        )
    }

    fn window_size(self) -> WindowSize {
        let width = self
            .cols
            .saturating_mul(self.cell_width_px as usize)
            .min(u16::MAX as usize) as u16;
        let height = self
            .rows
            .saturating_mul(self.cell_height_px as usize)
            .min(u16::MAX as usize) as u16;
        WindowSize {
            rows: self.rows.min(u16::MAX as usize) as u16,
            cols: self.cols.min(u16::MAX as usize) as u16,
            width,
            height,
        }
    }
}

impl GridEmulator {
    /// An emulator keeping `history` lines of scrollback rather than a live
    /// terminal's 1,000: for output read back whole.
    pub fn with_scrollback(cols: usize, rows: usize, history: usize) -> Self {
        Self::build(cols, rows, String::new(), history)
    }

    pub(crate) fn with_size_and_title(cols: usize, rows: usize, fallback_title: String) -> Self {
        Self::build(cols, rows, fallback_title, 1000)
    }

    fn build(cols: usize, rows: usize, fallback_title: String, history: usize) -> Self {
        let size = GridSize {
            cols: cols.max(2),
            rows: rows.max(2),
            cell_width_px: DEFAULT_CELL_WIDTH_PX,
            cell_height_px: DEFAULT_CELL_HEIGHT_PX,
        };
        let (notifications, events) = async_channel::unbounded();
        let osc_title = Arc::new(Mutex::new(None));
        let atomic_size = Arc::new(AtomicGridSize::new(size));
        let listener = GridListener {
            notifications: notifications.clone(),
            osc_title: osc_title.clone(),
            size: atomic_size.clone(),
        };
        let term = Crosswords::new(
            size.crosswords_size(),
            RioCursorShape::Block,
            listener,
            WindowId::from(0),
            0,
            history,
        );
        let core = Arc::new(GridCore {
            state: FairMutex::new(GridState {
                term,
                parser: Processor::default(),
            }),
            notifications,
            osc_title,
            fallback_title: Mutex::new(fallback_title),
            lifecycle: Mutex::new(GridLifecycle::default()),
            size: atomic_size,
        });
        Self { core, events }
    }

    /// Consume raw output bytes from the host PTY.
    ///
    /// Parser state is retained across calls, so chunks may split UTF-8,
    /// control sequences, OSC hyperlinks, or synchronized updates at any byte.
    pub fn feed(&self, bytes: &[u8]) {
        if bytes.is_empty() {
            return;
        }

        let (expired_sync, wakeup, sync_deadline) = {
            let mut state = self.core.state.lock();
            let expired_sync = stop_expired_sync(&mut state);
            let GridState { term, parser } = &mut *state;
            parser.advance(term, bytes);
            let wakeup = parser.sync_bytes_count() < bytes.len();
            let sync_deadline = parser.sync_timeout().sync_timeout();
            (expired_sync, wakeup, sync_deadline)
        };

        if expired_sync {
            let _ = self.core.notifications.try_send(GridEvent::Wakeup);
        }
        if wakeup {
            let _ = self.core.notifications.try_send(GridEvent::Wakeup);
        }
        if let Some(deadline) = sync_deadline {
            schedule_sync_timeout(Arc::downgrade(&self.core), deadline);
        }
    }

    /// Return rendering-relevant emulator events.
    ///
    /// Cloned receivers compete for events. Install one draining task and fan
    /// out from there when multiple consumers are needed.
    pub fn events(&self) -> async_channel::Receiver<GridEvent> {
        self.events.clone()
    }

    pub fn resize_with_cell_size_if_changed(
        &self,
        cols: usize,
        rows: usize,
        width_px: u32,
        height_px: u32,
    ) -> bool {
        let size = GridSize {
            cols: cols.max(2),
            rows: rows.max(2),
            cell_width_px: width_px.max(1),
            cell_height_px: height_px.max(1),
        };
        let mut state = self.core.state.lock();
        let current = self.core.size.load();
        if current == size {
            return false;
        }
        state.term.resize(size.crosswords_size());
        state.term.mark_fully_damaged();
        self.core.size.store(size);
        drop(state);
        let _ = self.core.notifications.try_send(GridEvent::Wakeup);
        true
    }

    #[cfg(feature = "pty")]
    pub(crate) fn window_size(&self) -> WindowSize {
        self.core.size.window_size()
    }

    pub fn clear(&self) {
        let mut state = self.core.state.lock();
        state.term.clear_saved_history();

        let cursor = state.term.grid.cursor.pos;
        state.term.grid.reset_region(..cursor.row);

        let line = state.term.grid[cursor.row][..Column(state.term.columns())]
            .iter()
            .copied()
            .enumerate()
            .collect::<Vec<_>>();
        for (index, cell) in line {
            state.term.grid[Line(0)][Column(index)] = cell;
        }

        state.term.grid.cursor.pos = Pos::new(Line(0), cursor.col);
        if state.term.screen_lines() > 1 {
            state.term.grid.reset_region(Line(1)..);
        }
        state.term.mark_fully_damaged();
        drop(state);
        let _ = self.core.notifications.try_send(GridEvent::Wakeup);
    }

    pub fn modify_other_keys(&self) -> Option<u8> {
        self.core.state.lock().term.modify_other_keys()
    }

    pub fn dimensions(&self) -> (usize, usize) {
        let size = self.core.size.load();
        (size.cols, size.rows)
    }

    /// Lines that have ever scrolled out of the screen, including those already
    /// dropped from the scrollback ring. Cheap enough to read before deciding
    /// how much history a snapshot should carry.
    pub fn scrolled_lines(&self) -> u64 {
        let state = self.core.state.lock();
        state.term.lines_evicted() + state.term.history_size() as u64
    }

    /// Snapshot the grid, additionally copying the scrollback rows that
    /// appeared since `scrolled_before` (oldest first, at most `budget`).
    ///
    /// `scrolled_before = 0` therefore asks for the whole retained ring, and
    /// the count is resolved under the same lock as the grid copy, so a
    /// concurrent PTY write cannot slip rows between the two reads.
    pub fn snapshot_since(&self, scrolled_before: u64, budget: usize) -> TermSnapshot {
        self.read(scrolled_before, budget, true)
    }

    /// Read the screen, without scrollback and without consuming renderer
    /// damage, so a diagnostic reader cannot starve the live projection.
    pub fn peek_snapshot(&self) -> TermSnapshot {
        self.read(0, 0, false)
    }

    fn read(&self, scrolled_before: u64, budget: usize, consume: bool) -> TermSnapshot {
        let mut state = self.core.state.lock();
        let history = (state.term.lines_evicted() + state.term.history_size() as u64)
            .saturating_sub(scrolled_before)
            .min(budget as u64) as usize;
        let cols = state.term.columns();
        let screen_lines = state.term.screen_lines();
        let display_offset = state.term.display_offset();
        let cursor_state = state.term.cursor();
        let display_cursor_line = cursor_state.pos.row.0 + display_offset as i32;
        let cursor = if display_cursor_line >= 0 && display_cursor_line < screen_lines as i32 {
            Some((display_cursor_line as usize, cursor_state.pos.col.0))
        } else {
            None
        };
        let damage = state
            .term
            .peek_damage_event()
            .unwrap_or(TerminalDamage::Noop);
        let mut row_damage = vec![false; screen_lines];
        match state.term.damage() {
            rio_vt::crosswords::TermDamage::Full => row_damage.fill(true),
            rio_vt::crosswords::TermDamage::Partial(lines) => {
                for line in lines {
                    if let Some(damaged) = row_damage.get_mut(line.line) {
                        *damaged = true;
                    }
                }
            }
        }
        if consume {
            state.term.reset_damage();
        }
        let visible_rows = state.term.visible_rows();
        if damage == TerminalDamage::Full {
            row_damage.fill(true);
        } else {
            for (damaged, row) in row_damage.iter_mut().zip(&visible_rows) {
                *damaged |= row.dirty;
            }
        }
        if consume {
            for row in 0..screen_lines {
                state.term.grid[Line(row as i32 - display_offset as i32)].dirty = false;
            }
        }
        let history_size = state.term.history_size();
        let history_rows = (1..=history.min(history_size))
            .rev()
            .map(|back| state.term.grid[Line(-(back as i32))].clone())
            .collect::<Vec<_>>();
        let styles = state.term.grid.styles().to_vec();
        let mut zero_width = HashMap::new();
        let mut links = HashMap::new();
        for square in visible_rows
            .iter()
            .chain(&history_rows)
            .flat_map(|row| row.inner.iter())
            .copied()
        {
            let Some(id) = square.extras_id().filter(|_| !square.is_bg_only()) else {
                continue;
            };
            let Some(extras) = state.term.grid.extras_table.get(id) else {
                continue;
            };
            if !extras.zerowidth.is_empty() {
                zero_width.insert(id, extras.zerowidth.clone());
            }
            if let Some(link) = &extras.hyperlink {
                links.insert(id, (link.uri().to_owned(), link.id().to_owned()));
            }
        }
        let mode = state.term.mode();
        let keyboard_mode = state.term.keyboard_mode();
        let lines_evicted = state.term.lines_evicted();
        let cursor_blinking = state.term.blinking_cursor;
        // Exit is fed after the child's last output, so read it while the grid
        // is still locked: a snapshot that reports the exit must also hold
        // every byte that preceded it.
        let (exited, exit_code) = {
            let lifecycle = self.core.lifecycle.lock_recover();
            (lifecycle.exited, lifecycle.exit_code)
        };
        drop(state);
        TermSnapshot {
            cols,
            screen_lines,
            visible_rows,
            history_rows,
            row_damage,
            damage,
            cursor_state,
            cursor,
            cursor_blinking,
            title: self.title(),
            exited,
            exit_code,
            history_size,
            lines_evicted,
            mode,
            keyboard_mode,
            styles,
            zero_width,
            links,
        }
    }

    /// Set the non-OSC title used when the emulated terminal has no title.
    pub fn set_fallback_title(&self, title: impl Into<String>) {
        *self.core.fallback_title.lock_recover() = title.into();
    }

    pub fn title(&self) -> String {
        self.core
            .osc_title
            .lock_recover()
            .clone()
            .unwrap_or_else(|| self.core.fallback_title.lock_recover().clone())
    }

    /// Return the title set by terminal output, excluding the fallback title.
    pub fn osc_title(&self) -> Option<String> {
        self.core.osc_title.lock_recover().clone()
    }

    /// Apply a host-side exit data event to this client-side snapshot.
    pub fn set_exited(&self, exit_code: Option<i32>) {
        let mut lifecycle = self.core.lifecycle.lock_recover();
        lifecycle.exited = true;
        lifecycle.exit_code = exit_code;
    }
}

fn stop_expired_sync(state: &mut GridState) -> bool {
    let expired = state
        .parser
        .sync_timeout()
        .sync_timeout()
        .is_some_and(|deadline| deadline <= Instant::now());
    if expired {
        let GridState { term, parser } = state;
        parser.stop_sync(term);
    }
    expired
}

fn schedule_sync_timeout(core: Weak<GridCore>, deadline: Instant) {
    let _timer = thread::Builder::new()
        .name("tcode-terminal-sync-timeout".into())
        .spawn(move || {
            thread::sleep(deadline.saturating_duration_since(Instant::now()));
            let Some(core) = core.upgrade() else {
                return;
            };
            let expired = {
                let mut state = core.state.lock();
                stop_expired_sync(&mut state)
            };
            if expired {
                let _ = core.notifications.try_send(GridEvent::Wakeup);
            }
        });
}

fn query_color(index: usize) -> ColorRgb {
    const ANSI: [u32; 16] = [
        0x1f2329, 0xe45649, 0x50a14f, 0xc18401, 0x4078f2, 0xa626a4, 0x0184bc, 0xabb2bf, 0x5c6370,
        0xff616e, 0x7bc275, 0xe5c07b, 0x61afef, 0xc678dd, 0x56b6c2, 0xffffff,
    ];
    let value = match index {
        0..=15 => ANSI[index],
        16..=231 => {
            let n = (index - 16) as u32;
            let component = |value: u32| if value == 0 { 0 } else { 55 + value * 40 };
            (component(n / 36) << 16) | (component((n % 36) / 6) << 8) | component(n % 6)
        }
        232..=255 => {
            let gray = 8 + (index - 232) as u32 * 10;
            (gray << 16) | (gray << 8) | gray
        }
        index if index == NamedColor::Background as usize => 0xffffff,
        index if index == NamedColor::Cursor as usize => 0x1f2329,
        _ => 0x1f2329,
    };
    ColorRgb {
        r: (value >> 16) as u8,
        g: (value >> 8) as u8,
        b: value as u8,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{DEFAULT_COLS, DEFAULT_ROWS};

    fn emulator() -> GridEmulator {
        GridEmulator::with_size_and_title(DEFAULT_COLS, DEFAULT_ROWS, String::new())
    }

    #[test]
    fn snapshots_consume_damage_but_peeks_preserve_it() {
        let emulator = emulator();
        emulator.snapshot_since(0, 0);
        emulator.feed(b"written");
        assert!(emulator.peek_snapshot().row_damage[0]);

        let snapshot = emulator.snapshot_since(0, 0);
        assert!(snapshot.row_damage[0]);
        assert!(snapshot.row_damage[1..].iter().all(|damaged| !damaged));
        assert_eq!(snapshot.damage, TerminalDamage::Partial);
        let idle = emulator.snapshot_since(0, 0);
        assert_eq!(idle.damage, TerminalDamage::Noop);
        assert!(idle.row_damage.iter().all(|damaged| !damaged));

        emulator.clear();
        let cleared = emulator.snapshot_since(0, 0);
        assert_eq!(cleared.damage, TerminalDamage::Full);
        assert!(cleared.row_damage.iter().all(|damaged| *damaged));
        assert_eq!(cleared.history_size, 0);
    }

    #[test]
    fn emulator_answers_size_queries_and_keeps_the_clipboard_unread() {
        let emulator = emulator();
        let events = emulator.events();
        emulator.resize_with_cell_size_if_changed(42, 9, 10, 20);

        emulator.feed(b"\x1b[14t");

        assert!(
            std::iter::from_fn(|| events.try_recv().ok())
                .any(|event| { event == GridEvent::Input(b"\x1b[4;180;420t".to_vec()) })
        );
        emulator.feed(b"\x1b]52;c;dGNvZGU=\x07");
        assert!(std::iter::from_fn(|| events.try_recv().ok()).any(|event| {
            event
                == GridEvent::ClipboardStore {
                    kind: ClipboardType::Clipboard,
                    text: "tcode".to_string(),
                }
        }));

        emulator.feed(b"\x1b]52;c;?\x07");
        assert!(
            std::iter::from_fn(|| events.try_recv().ok())
                .any(|event| { event == GridEvent::Input(b"\x1b]52;c;\x07".to_vec()) })
        );
    }
}
